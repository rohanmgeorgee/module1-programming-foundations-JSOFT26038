#include <iostream>
using namespace std;
int main()
{
    cout << 7 / 2 << endl;    // 3
    cout << 7 % 2 << endl;    // 1
    cout << 7.0 / 2 << endl;  // 3.5
    cout << (5 == 5) << endl; // 1
    cout << (5 != 5) << endl; // 0
    int x = 5;
    cout << x << " ";
    x++;
    cout << x << endl; // 5 6
    return 0;
}